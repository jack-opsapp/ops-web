/**
 * Every classified table. Parent-scoped children come first because the
 * deletion cascade must clear them before their parents disappear.
 */
export const COMPANY_DATA_MANIFEST: readonly ManifestEntry[] = [
  ...PARENT_SCOPED_DATA,
  ...COMPANY_SCOPED_DATA,
];

let indexCache: Map<string, ManifestEntry> | null = null;

/** Table name → entry. */
export function manifestByTable(): Map<string, ManifestEntry> {
  if (!indexCache) {
    indexCache = new Map(COMPANY_DATA_MANIFEST.map((e) => [e.table, e]));
  }
  return indexCache;
}

/**
 * The ordered deletion sequence: parent-scoped children, then company-scoped
 * tables by foreign-key depth, then the company row. Retained tables are
 * excluded — they are deliberately left alone.
 */
export function deletionPlan(): ManifestEntry[] {
  return COMPANY_DATA_MANIFEST.filter((e) => e.deleteStrategy !== "retain");
}

/** Serializable plan passed verbatim to the transactional purge function. */
export function transactionalPurgePlan(): TransactionalPurgePlan {
  return {
    manifest_version: MANIFEST_VERSION,
    cycle_breakers: FK_CYCLE_BREAKERS,
    steps: deletionPlan().map((entry) => ({
      ...entry,
      definer_purged: isDefinerPurged(entry.table),
    })),
  };
}

/** Everything the customer is entitled to take with them. */
export function exportPlan(): ManifestEntry[] {
  return COMPANY_DATA_MANIFEST.filter((e) => e.export);
}

/** Split `ids` into `in.()`-sized chunks. */
export function chunkIds(ids: readonly string[]): string[][] {
  const chunks: string[][] = [];
  for (let i = 0; i < ids.length; i += ID_CHUNK_SIZE) {
    chunks.push(ids.slice(i, i + ID_CHUNK_SIZE) as string[]);
  }
  return chunks;
}
