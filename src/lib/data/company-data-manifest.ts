/**
 * OPS Web — Company Data Manifest
 *
 * The single, authoritative inventory of every table that holds data belonging
 * to one company. `/api/data/export` and `/api/data/delete-account` are both
 * driven by it; neither route names a table anywhere else.
 *
 * ── Why this exists ────────────────────────────────────────────────────────
 * Both routes used to carry their own hardcoded list, frozen years ago. They
 * addressed `estimate_line_items`, `invoice_line_items` and `tasks` — none of
 * which have ever existed (the real tables are `line_items` and
 * `project_tasks`) — and swallowed each per-table error, so account deletion
 * answered "success" while leaving virtually all modern data behind, and every
 * export silently omitted tasks and line items (bug 241830b2).
 *
 * ── Absence is never an exclusion ──────────────────────────────────────────
 * Every table the live schema places inside a company's data is accounted for
 * here — either classified below, or declared in `OUT_OF_SCOPE_TABLES` with a
 * reason. A reader must never have to guess whether a missing table was
 * considered and rejected or simply overlooked; that ambiguity IS the bug this
 * file exists to kill, so the two states are made distinguishable by
 * construction.
 *
 * `tests/integration/company-data-manifest.test.ts` enforces it with two
 * guards of unequal strength.
 *
 * PRIMARY — against `company-data-scope-snapshot.ts`, a checked-in picture of
 * the live schema generated by the documented SQL (tables with `company_id`,
 * plus every base table reaching one through a declared foreign key, to
 * fixpoint):
 *
 *   1. Every table in `IN_SCOPE_SNAPSHOT` MUST appear in the manifest or in
 *      `OUT_OF_SCOPE_TABLES`.
 *   2. The manifest MUST NOT name anything outside `IN_SCOPE_SNAPSHOT`, apart
 *      from `TENANT_TABLE` — no query can derive the company row, since it has
 *      neither a `company_id` nor a foreign key into scope, so the manifest
 *      adds it explicitly as the root.
 *   3. Every table in `AUTH_IDENTITY_SNAPSHOT` MUST be declared out of scope.
 *      These hang off Supabase Auth identities rather than `public.users`, so
 *      the closure cannot reach them even though they look user-owned; naming
 *      them forces a deliberate decision instead of a silent omission.
 *
 * SECONDARY — against the checked-in generated types,
 * `src/lib/types/database.types.ts`: every table in its `Tables:` block that
 * carries a `company_id` must be classified, and the manifest must not name a
 * table the types do not know, except the documented
 * `UNTYPED_TABLE_ALLOWLIST`. This guard is deliberately the weaker of the two
 * — it CANNOT see the backend tables the generated types have not caught up to
 * (every one of them is enumerated in `UNTYPED_TABLE_ALLOWLIST` below), so a
 * table absent from the types could slip past it unnoticed. It must never be
 * the only guard; the snapshot is what actually holds the line.
 *
 * That allowlist shrinks as main regenerates the types, and the
 * stale-allowlist assertion is what forces it to be pruned — treat a failure
 * there as the guard working, not as breakage.
 *
 * Tests cannot reach production, so refreshing those two checked-in artefacts
 * is what forces a new table to be consciously classified. After any migration
 * that adds a company-scoped table, regenerate BOTH the snapshot (see
 * `company-data-scope-snapshot.ts` for the exact queries) and the types; the
 * completeness tests then fail until the table is given a strategy and an
 * export decision here, or an explicit reason for being excluded.
 *
 * ── Derived from the live schema ───────────────────────────────────────────
 * Classification was derived against prod (`ijeekuhbatykdomumfjx`) on
 * 2026-07-29. Three queries reproduce it:
 *
 *   -- 1. every company-scoped base table, its tenant column type, and whether
 *   --    it can be tombstoned at all
 *   SELECT c.table_name, c.data_type, EXISTS (
 *            SELECT 1 FROM information_schema.columns d
 *            WHERE d.table_schema = 'public' AND d.table_name = c.table_name
 *              AND d.column_name = 'deleted_at')
 *   FROM information_schema.columns c
 *   JOIN information_schema.tables t
 *     ON t.table_schema = c.table_schema AND t.table_name = c.table_name
 *    AND t.table_type = 'BASE TABLE'
 *   WHERE c.table_schema = 'public' AND c.column_name = 'company_id';
 *
 *   -- 2. tables with NO company_id that hang off a company-scoped parent by
 *   --    foreign key (invisible to a company_id-only sweep)
 *   -- 3. blocking (NO ACTION / RESTRICT) foreign keys between them, which fix
 *   --    the deletion order and expose the two mutual cycles
 *
 * At the time of writing that is 218 in-scope tables — 180 carrying
 * `company_id` and 38 reaching one by foreign key — plus the `companies` row
 * itself, and 5 auth-identity tables declared out of scope.
 *
 * ── How to classify a new table ────────────────────────────────────────────
 * `export: true`  — the customer's own business records: jobs, tasks, clients,
 *                   money documents, catalog and pricing, photos, notes, site
 *                   visits, leads, calendar, expenses, settings.
 * `export: false` — machinery the system created to run itself: queues,
 *                   outboxes, claims, locks, staging, provider bookkeeping,
 *                   agent internals, telemetry, delivery receipts. Anything
 *                   holding a credential (OAuth tokens, portal tokens) is
 *                   ALWAYS `export: false`.
 * `deleteStrategy` follows the schema: `soft` when the table has a `deleted_at`
 *                   column, `hard` when it does not. `retain` is reserved for
 *                   the handful of rows with a legal, financial or referential
 *                   reason to outlive the account — each carries its reason.
 *
 * Every `retain` and every `export: false` entry states why, in `reason`.
 *
 * ── Deletion ordering ──────────────────────────────────────────────────────
 * `COMPANY_SCOPED_DATA` is ordered, and the order is load-bearing: a hard
 * DELETE fails if a surviving row still references the target. Entries are
 * grouped by foreign-key depth, deepest first, so children are always purged
 * before their parents, and `companies` is tombstoned last. The groups (each
 * derived from prod `pg_constraint`, blocking edges only) are:
 *
 *   depth 5  email_outbound_edit_promotions
 *   depth 4  email_outbound_learning_queue
 *   depth 3  email_conversion_photo_objects, email_send_intents
 *   depth 2  approved_action_email_intents,
 *            email_assignment_contact_form_draft_queue,
 *            email_conversion_photo_jobs, opportunity_assignment_deliveries,
 *            pending_auto_sends
 *   depth 1  activities, agent_knowledge_graph, agent_memories,
 *            attachment_inspections, email_attachments,
 *            email_import_provider_operations, line_items,
 *            opportunity_assignment_events,
 *            opportunity_conversion_notification_deliveries, portal_sessions,
 *            task_schedule_automation_outbox,
 *            unassigned_lead_assignment_deliveries
 *   depth 0  everything else, then `companies`
 *
 * Two pairs reference each other, so no ordering can satisfy both directions.
 * `FK_CYCLE_BREAKERS` nulls the nullable side of each cycle first — on rows
 * that are about to be deleted anyway — which turns each cycle into a chain.
 *
 * Verified 2026-07-29: with this classification, zero surviving rows anywhere
 * in `public` hold a blocking foreign key into a table this manifest purges.
 *
 * NEVER import this from client-side code.
 */

