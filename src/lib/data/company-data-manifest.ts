export type DeleteStrategy = "soft" | "hard" | "retain";

interface ManifestEntryBase {
  readonly table: string;
  /** True only when the table actually has a `deleted_at` column. */
  readonly softDeletable: boolean;
  readonly deleteStrategy: DeleteStrategy;
  /** Is this the customer's own data, or machinery that runs the product? */
  readonly export: boolean;
  /** Required for every `retain` entry and every `export: false` entry. */
  readonly reason?: string;
}

export interface CompanyScopedEntry extends ManifestEntryBase {
  readonly scope: "company";
  /** `company_id` everywhere except the tenant row itself, which uses `id`. */
  readonly companyColumn: string;
  /** The column's Postgres type. The value passed is a string either way. */
  readonly companyColumnType: "uuid" | "text";
}

export interface ParentScopedEntry extends ManifestEntryBase {
  readonly scope: "parent";
  /** The company-scoped (or itself parent-scoped) table this hangs off. */
  readonly parentTable: string;
  /** The NOT NULL foreign-key column on THIS table pointing at the parent. */
  readonly parentColumn: string;
}

export type ManifestEntry = CompanyScopedEntry | ParentScopedEntry;

export type TransactionalPurgeStep = ManifestEntry & {
  readonly definer_purged: boolean;
};

export interface TransactionalPurgePlan {
  readonly manifest_version: string;
  readonly cycle_breakers: typeof FK_CYCLE_BREAKERS;
  readonly steps: readonly TransactionalPurgeStep[];
}

/**
 * A table the live schema puts near a company's data that this cascade
 * deliberately does NOT touch. Declaring it is the point: an excluded table
 * must be a reviewable decision, never an omission.
 */
export interface OutOfScopeEntry {
  readonly table: string;
  /** Why it is not a company's data. Required — there are no silent exclusions. */
  readonly reason: string;
}

